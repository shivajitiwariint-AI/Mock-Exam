/** @type {import('next').NextConfig} */
const isDev = process.env.NODE_ENV !== 'production'

// Next.js injects inline bootstrap scripts, so 'unsafe-inline' is required
// unless a nonce-based CSP is wired through middleware. 'unsafe-eval' is only
// needed by the development server (HMR).
const contentSecurityPolicy = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ''}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "connect-src 'self' https:",
  "media-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join('; ')

const nextConfig = {
  experimental: {
    serverComponentsExternalPackages: ['@prisma/adapter-mariadb', 'mariadb'],
  },
  poweredByHeader: false,
  async redirects() {
    return [
      {
        source: '/question-bank',
        destination: '/interview/questions',
        permanent: false,
      },
    ];
  },
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'Content-Security-Policy', value: contentSecurityPolicy },
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'X-Frame-Options', value: 'DENY' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          {
            key: 'Permissions-Policy',
            value: 'camera=(), microphone=(), geolocation=(), payment=()',
          },
          {
            key: 'Strict-Transport-Security',
            value: 'max-age=31536000; includeSubDomains',
          },
        ],
      },
    ];
  },
};

export default nextConfig;
